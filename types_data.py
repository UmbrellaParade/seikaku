def pick_questions():
    """各軸から4問ずつランダムに選んで16問返す"""
    selected = []
    for axis, questions in QUESTION_POOL.items():
        picked = random.sample(questions, 4)
        for i, q in enumerate(picked):
            q = dict(q)
            q["axis"] = axis
            q["options"] = [dict(o) for o in q["options"]]
            selected.append(q)
    # シャッフルして返す
    random.shuffle(selected)
    return selected


